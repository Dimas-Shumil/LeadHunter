export const searchTerms = Object.fromEntries(nicheGroups.flatMap(group =>
  group.items.map(([name, terms]) => [name, terms])
));
export const niches = Object.fromEntries(nicheGroups.flatMap(group =>
  group.items.map(([name, , osm]) => [name, osm])
));
export const nicheGroupsForUI = nicheGroups.map(group => ({
  name: group.name,
  items: group.items.map(([name, , osm]) => ({ name, osm: osm.length > 0 })),
}));

export function searchPhrases(selected = [], customQuery = "") {
  const phrases = (selected || []).flatMap(niche =>
    (searchTerms[niche] || []).map(term => ({ niche, term }))
  );
  const query = String(customQuery || "").trim();
  if (query) phrases.push({ niche: `Поиск: ${query}`, term: query });
  return phrases;
}
